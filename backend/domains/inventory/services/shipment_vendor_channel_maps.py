def parse_shipment_vendor_primary_overrides_from_payload(data: object) -> dict[str, str]:
    """JSON 객체: { \"판매처 문자열\": \"자사\"|\"쿠팡\"|… } → normalize 키 → 내부 1차."""
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError("shipment_vendor_primary_overrides는 JSON 객체여야 합니다.")
    out: dict[str, str] = {}
    for raw_k, raw_v in data.items():
        nk = normalize_shipment_vendor_key(raw_k)
        if not nk:
            continue
        label = str(raw_v).strip()
        if label not in SHIPMENT_VENDOR_UI_LABEL_TO_INTERNAL:
            raise ValueError(f"허용되지 않는 구분입니다: {label}")
        out[nk] = SHIPMENT_VENDOR_UI_LABEL_TO_INTERNAL[label]
    return out


def resolve_vendor_primary_with_overrides(
    vendor_raw: object,
    request_overrides_internal: dict[str, str] | None,
) -> str | None:
    """요청으로 넘긴 임시 매핑(정규화 키)을 고정 표보다 우선."""
    nk = normalize_shipment_vendor_key(vendor_raw)
    if not nk:
        return None
    if request_overrides_internal and nk in request_overrides_internal:
        return request_overrides_internal[nk]
    return resolve_vendor_primary(vendor_raw)
